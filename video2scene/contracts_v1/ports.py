"""Internal ports consume schema-validated wire dictionaries."""
from typing import AsyncIterator, Protocol
from .dto import *  # noqa: F403
from .core import ExecutionContext


class SceneRepository(Protocol):
    async def inspect(self, request: ToolRequest, context: ExecutionContext) -> SceneView: ...
    async def prepare_patch(self, request: ToolRequest, context: ExecutionContext) -> CandidateRef: ...
    async def prepare_refinement(self, request: ToolRequest, context: ExecutionContext) -> CandidateRef: ...
    async def prepare_extension(self, request: dict, context: ExecutionContext) -> CandidateRef: ...
    async def read_candidate(self, candidate_id: str, candidate_hash: str, context: ExecutionContext) -> CandidateSnapshot: ...
    async def attach_build(self, candidate_id: str, candidate_hash: str, build_output: BuildOutput, context: ExecutionContext) -> CandidateRef: ...
    async def commit(self, request: ToolRequest, context: ExecutionContext) -> CommitResult: ...
    async def history(self, request: ToolRequest, context: ExecutionContext) -> HistoryResult | CommitResult: ...


class EvidenceService(Protocol):
    async def select(self, request: ToolRequest, context: ExecutionContext) -> EvidenceBundle: ...
    async def select_for_extension(self, request: ToolRequest, candidate_id: str, candidate_hash: str,
                                   context: ExecutionContext, *, frame_ids=None) -> EvidenceBundle: ...


class AssetBackend(Protocol):
    async def build(self, candidate_snapshot: CandidateSnapshot, job_context: ExecutionContext) -> BuildOutput: ...
    async def refine(self, refine_spec: dict, scene_snapshot: SceneSnapshot, evidence: EvidenceBundle, job_context: ExecutionContext) -> BuildOutput: ...
    async def render(self, candidate_snapshot: CandidateSnapshot, evidence: EvidenceBundle, view_mode: str, job_context: ExecutionContext) -> RenderReport: ...
    async def collisions(self, candidate_snapshot: CandidateSnapshot, method: str, job_context: ExecutionContext) -> CollisionReport: ...


class CandidateValidator(Protocol):
    async def validate(self, candidate_snapshot: CandidateSnapshot, evidence: EvidenceBundle, criteria: dict, job_context: ExecutionContext) -> ValidationReport: ...
    async def get_report(self, validation_id: str, context: ExecutionContext) -> ValidationReport: ...


class JobService(Protocol):
    async def submit(self, request: ToolRequest, context: ExecutionContext) -> JobReceipt: ...
    async def control(self, request: ToolRequest, context: ExecutionContext) -> JobRecord: ...


class AgentProvider(Protocol):
    def run(self, session: SessionSpec) -> AsyncIterator[AgentEvent]: ...

